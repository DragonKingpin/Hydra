package com.walnut.odin.task.troll;

public class InstanceLaunchException extends ElevationException {

    public InstanceLaunchException() {
        super();
    }

    public InstanceLaunchException( String message ) {
        super(message);
    }

    public InstanceLaunchException( String message, Throwable cause ) {
        super(message, cause);
    }

    public InstanceLaunchException( Throwable cause ) {
        super(cause);
    }

}
