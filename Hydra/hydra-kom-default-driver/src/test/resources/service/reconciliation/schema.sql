CREATE TABLE hydra_service_instances (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    guid VARCHAR(82) UNIQUE NOT NULL,
    service_guid VARCHAR(82),
    deploy_guid VARCHAR(82),
    runtime_node_guid VARCHAR(82),
    runtime_node_id VARCHAR(82),
    client_id BIGINT,
    transport_type VARCHAR(64),
    remote_address VARCHAR(255),
    endpoint_protocol VARCHAR(64),
    endpoint_host VARCHAR(255),
    endpoint_port INT,
    endpoint_path VARCHAR(255),
    endpoint_address VARCHAR(512),
    status VARCHAR(64),
    status_reason VARCHAR(1024),
    version VARCHAR(64),
    zone VARCHAR(64),
    weight INT,
    register_time TIMESTAMP,
    last_heartbeat_time TIMESTAMP,
    expire_time TIMESTAMP,
    offline_time TIMESTAMP,
    connection_count INT NOT NULL,
    latest_start_time TIMESTAMP,
    latest_end_time TIMESTAMP,
    metadata_json TEXT
);
CREATE INDEX idx_instance_status_id ON hydra_service_instances(status, id);
CREATE TABLE hydra_service_runtime_node (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    guid VARCHAR(82) UNIQUE NOT NULL,
    service_guid VARCHAR(82),
    node_id VARCHAR(82),
    alias VARCHAR(255),
    status VARCHAR(64),
    version VARCHAR(64),
    zone VARCHAR(64),
    metadata_json TEXT,
    latest_instance_guid VARCHAR(82),
    latest_start_time TIMESTAMP,
    latest_end_time TIMESTAMP,
    last_heartbeat_time TIMESTAMP,
    create_time TIMESTAMP,
    update_time TIMESTAMP
);
